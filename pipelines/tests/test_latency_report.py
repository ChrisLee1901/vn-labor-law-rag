def test_unfinished_and_malformed_spans_are_skipped(tmp_path):
    bad = [
        {"name": "llm", "startTime": "2026-12-02T10:00:00Z", "endTime": None},
        {"name": "llm", "startTime": "oops", "endTime": "2026-12-02T10:00:01Z"},
        {
            "name": "llm",
            "startTime": "2026-12-02T10:00:05Z",
            "endTime": "2026-12-02T10:00:01Z",
        },
        {"name": "llm"},
    ]
    rc, _, out = run(tmp_path, [bad + [obs("llm", 250)]])
    assert rc == 0 and "| llm | 1 | 250 | 250 |" in out.read_text(encoding="utf-8")


