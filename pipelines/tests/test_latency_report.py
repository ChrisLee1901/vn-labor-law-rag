def test_real_http_path_sends_basic_auth_and_reports_status_only(tmp_path, capsys):
    """Đường urllib thật tới server loopback (không ra mạng ngoài)."""
    seen = {}

    class H(BaseHTTPRequestHandler):
        def do_GET(self):
            seen["auth"], seen["path"] = self.headers["Authorization"], self.path
            if "fail" in seen:
                self.send_response(500)
                self.end_headers()
                return
            body = json.dumps({"data": [obs("embed", 30)], "meta": {}}).encode()
            self.send_response(200)
            self.send_header("content-length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, format, *args):
            pass

    srv = HTTPServer(("127.0.0.1", 0), H)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    env = {**ENV, "LANGFUSE_HOST": f"http://127.0.0.1:{srv.server_port}/"}
    out = tmp_path / "l.md"
    try:
        assert lr.main(["--out", str(out)], env=env, now=NOW) == 0
        assert seen["auth"].startswith("Basic ") and seen["path"].startswith(
            "/api/public/v2/observations?"
        )
        assert "| embed | 1 | 30 | 30 |" in out.read_text(encoding="utf-8")
        seen["fail"] = True
        capsys.readouterr()
        assert lr.main(["--out", str(tmp_path / "x.md")], env=env, now=NOW) == 3
        err = capsys.readouterr().err
        assert "HTTP 500" in err and "pk-secret" not in err and "127.0.0.1" not in err
    finally:
        srv.shutdown()
