def test_auth_is_basic_and_secrets_never_printed(tmp_path, capsys):
    rc, api, out = run(tmp_path, [[obs("llm", 10)]])
    auth = api.calls[0][1]["Authorization"]
    import base64

    assert (
        auth
        == "Basic " + base64.b64encode(b"pk-secret-public:sk-secret-private").decode()
    )
    seen = capsys.readouterr()
    text = seen.out + seen.err + out.read_text(encoding="utf-8")
    for secret in ("pk-secret-public", "sk-secret-private", auth.split()[1]):
        assert secret not in text


